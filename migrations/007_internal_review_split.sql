-- Separate Inner Circle review workflow from the official External DCI.

create table if not exists internal_documents (
  id bigint generated by default as identity primary key,
  project_id bigint not null,
  document_number text not null,
  document_title text not null,
  discipline text not null,
  parent_document_id bigint references internal_documents(id) on delete set null,
  assigned_contractor_id uuid,
  assigned_consultant_id uuid,
  status text not null default 'waiting_contractor_review'
    check (status in (
      'draft',
      'waiting_contractor_review',
      'contractor_reviewing',
      'waiting_consultant_response',
      'consultant_responding',
      'waiting_contractor_verification',
      'ready_for_external_submission',
      'sent_to_external_dci',
      'closed'
    )),
  current_version_number integer not null default 0,
  created_by uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(project_id, document_number)
);
create index if not exists idx_internal_documents_project_status
  on internal_documents(project_id, status);
create index if not exists idx_internal_documents_discipline
  on internal_documents(project_id, discipline);

create table if not exists internal_document_versions (
  id uuid primary key default gen_random_uuid(),
  project_id bigint not null,
  internal_document_id bigint not null references internal_documents(id) on delete cascade,
  version_number integer not null,
  version_label text not null,
  revision_date date not null,
  remarks text,
  storage_bucket text not null default 'project-documents',
  storage_path text not null,
  original_filename text not null,
  generated_filename text not null,
  mime_type text not null default 'application/pdf',
  size_bytes bigint not null default 0,
  sha256_hash text,
  uploaded_by uuid not null,
  uploaded_by_org text not null default 'consultant',
  is_current boolean not null default true,
  uploaded_at timestamptz not null default now(),
  viewer_file_id uuid references document_files(id) on delete set null,
  viewer_version_id uuid references document_versions(id) on delete set null,
  unique(internal_document_id, version_number)
);
create index if not exists idx_internal_versions_document
  on internal_document_versions(internal_document_id, version_number desc);

create table if not exists internal_response_packages (
  id uuid primary key default gen_random_uuid(),
  project_id bigint not null,
  internal_document_id bigint not null references internal_documents(id) on delete cascade,
  source_version_id uuid not null references internal_document_versions(id) on delete restrict,
  submitted_version_id uuid references internal_document_versions(id) on delete set null,
  package_number integer not null,
  status text not null default 'submitted'
    check (status in ('draft','submitted','accepted','reopened')),
  closure_method text not null
    check (closure_method in ('comment_only','updated_file')),
  closure_remarks text not null,
  package_remarks text,
  submitted_by uuid not null,
  submitted_at timestamptz not null default now(),
  accepted_by uuid,
  accepted_at timestamptz,
  unique(internal_document_id, package_number)
);

create table if not exists internal_response_package_items (
  id uuid primary key default gen_random_uuid(),
  package_id uuid not null references internal_response_packages(id) on delete cascade,
  comment_id uuid not null references review_comments(id) on delete restrict,
  response_id uuid references review_comment_responses(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(package_id, comment_id)
);

create table if not exists external_submission_queue (
  id uuid primary key default gen_random_uuid(),
  project_id bigint not null,
  internal_document_id bigint not null references internal_documents(id) on delete cascade,
  internal_version_id uuid not null references internal_document_versions(id) on delete restrict,
  status text not null default 'ready' check (status in ('ready','submitted','cancelled')),
  requested_by uuid not null,
  requested_at timestamptz not null default now(),
  submitted_at timestamptz,
  unique(internal_document_id, internal_version_id)
);

-- Existing CRS comments now explicitly identify the internal document/version context.
alter table review_comments
  add column if not exists internal_document_id bigint references internal_documents(id) on delete cascade,
  add column if not exists internal_version_id uuid references internal_document_versions(id) on delete set null,
  add column if not exists response_package_id uuid references internal_response_packages(id) on delete set null;

create index if not exists idx_review_comments_internal_context
  on review_comments(project_id, internal_document_id, internal_version_id, status);

