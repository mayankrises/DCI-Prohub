create table if not exists dci_templates (
    id bigint generated by default as identity primary key,
    template_name text not null,
    description text,
    original_filename text,
    storage_bucket text not null default 'dci-workbooks',
    storage_path text,
    workbook_hash text,
    engine_version integer not null default 2,
    layout_definition jsonb not null default '{}'::jsonb,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists projects (
    id bigint generated by default as identity primary key,
    project_name text not null,
    contractor text not null default '',
    client text not null default '',
    review_period_days integer not null default 21 check (review_period_days between 1 and 90),
    template_id bigint references dci_templates(id),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table if exists imports add column if not exists project_id bigint references projects(id);
alter table if exists imports add column if not exists template_id bigint references dci_templates(id);
alter table if exists imports add column if not exists layout_definition jsonb not null default '{}'::jsonb;

alter table if exists documents add column if not exists project_id bigint references projects(id);

alter table if exists document_history add column if not exists event_date date;
alter table if exists document_history add column if not exists metadata jsonb not null default '{}'::jsonb;

create index if not exists idx_imports_project_id on imports(project_id);
create index if not exists idx_documents_project_id on documents(project_id);
create index if not exists idx_projects_active on projects(is_active);

-- Preserve older single-project imports by attaching them to one legacy project.
do $$
declare
    v_project_id bigint;
begin
    if exists (select 1 from imports where project_id is null) then
        select id into v_project_id
        from projects
        where project_name = 'Legacy DCI Project'
        order by id
        limit 1;

        if v_project_id is null then
            insert into projects(project_name, contractor, client)
            values ('Legacy DCI Project', '', '')
            returning id into v_project_id;
        end if;

        update imports set project_id = v_project_id where project_id is null;
    end if;
end $$;

update documents d
set project_id = i.project_id
from imports i
where d.import_id = i.id and d.project_id is null;

create table if not exists app_users (
    id uuid primary key default gen_random_uuid(),
    name text not null,
    email text not null unique,
    role text not null default 'viewer',
    initials text,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists project_members (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    user_id uuid not null references app_users(id) on delete cascade,
    role text not null default 'viewer',
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(project_id, user_id)
);

create index if not exists idx_project_members_project on project_members(project_id);
create index if not exists idx_project_members_user on project_members(user_id);
